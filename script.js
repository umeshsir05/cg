// Application State
let currentChapterId = 1;
let currentQuestionIndex = 0;

// DOM Elements
const menuToggle = document.getElementById('menuToggle');
const sidebar = document.getElementById('sidebar');
const closeSidebar = document.getElementById('closeSidebar');
const overlay = document.getElementById('overlay');
const chapterNav = document.getElementById('chapterNav');
const themeToggle = document.getElementById('themeToggle');
const currentChapterTitle = document.getElementById('currentChapterTitle');
const quizStatus = document.getElementById('quizStatus');
const questionArea = document.getElementById('questionArea');
const prevBtn = document.getElementById('prevBtn');
const nextBtn = document.getElementById('nextBtn');
const jumpInput = document.getElementById('jumpInput');
const jumpBtn = document.getElementById('jumpBtn');

// Sidebar Control
function toggleDrawer() {
    sidebar.classList.toggle('active');
    overlay.classList.toggle('active');
}

menuToggle.addEventListener('click', toggleDrawer);
closeSidebar.addEventListener('click', toggleDrawer);
overlay.addEventListener('click', toggleDrawer);

// Populate Chapters in Sidebar
function initChapterList() {
    chapterNav.innerHTML = '';
    chapters.forEach((chap) => {
        const btn = document.createElement('button');
        btn.className = `chapter-item ${chap.id === currentChapterId ? 'active' : ''}`;
        btn.textContent = chap.title;
        btn.onclick = () => {
            currentChapterId = chap.id;
            currentQuestionIndex = 0;
            initChapterList();
            loadQuiz();
            toggleDrawer();
        };
        chapterNav.appendChild(btn);
    });
}

// Dark Mode Toggle
themeToggle.addEventListener('click', () => {
    const isDark = document.body.getAttribute('data-theme') === 'dark';
    if (isDark) {
        document.body.removeAttribute('data-theme');
        themeToggle.querySelector('.theme-icon').textContent = '🌙';
        localStorage.setItem('cg_gk_theme', 'light');
    } else {
        document.body.setAttribute('data-theme', 'dark');
        themeToggle.querySelector('.theme-icon').textContent = '☀️';
        localStorage.setItem('cg_gk_theme', 'dark');
    }
});

// Render Quiz Content & Save Progress
function loadQuiz() {
    const activeChap = chapters.find(c => c.id === currentChapterId);
    currentChapterTitle.textContent = activeChap.title;
    
    const questions = mcqDatabase[currentChapterId] || [];
    quizStatus.textContent = questions.length ? `प्रश्न ${currentQuestionIndex + 1} / ${questions.length}` : "कोई प्रश्न उपलब्ध नहीं है";

    if (!questions.length) {
        questionArea.innerHTML = `<p style="padding: 1rem 0; color: var(--text-secondary);">इस अध्याय के प्रश्न जल्द ही जोड़े जाएंगे।</p>`;
        prevBtn.style.display = 'none';
        nextBtn.style.display = 'none';
        if (jumpInput) jumpInput.value = '';
        return;
    }

    // Auto-Save progress to localStorage
    localStorage.setItem('cg_gk_last_chapter', currentChapterId);
    localStorage.setItem('cg_gk_last_question', currentQuestionIndex);

    // Sync Jump Box Input
    if (jumpInput) {
        jumpInput.max = questions.length;
        jumpInput.value = currentQuestionIndex + 1;
    }

    prevBtn.style.display = 'inline-block';
    nextBtn.style.display = 'inline-block';
    prevBtn.disabled = currentQuestionIndex === 0;
    nextBtn.disabled = currentQuestionIndex === questions.length - 1;

    const q = questions[currentQuestionIndex];
    let html = `
        <div class="question-title">Q${currentQuestionIndex + 1}. ${q.question}</div>
        <div class="options-grid">
    `;

    q.options.forEach((opt, idx) => {
        html += `<button class="option-btn" onclick="checkAnswer(${idx})">${opt}</button>`;
    });

    html += `</div><div id="explanationContainer"></div>`;
    questionArea.innerHTML = html;
}

// Option Click & Answer Checking
window.checkAnswer = function(selectedIndex) {
    const questions = mcqDatabase[currentChapterId];
    const q = questions[currentQuestionIndex];
    const optionButtons = document.querySelectorAll('.option-btn');

    optionButtons.forEach((btn, idx) => {
        btn.disabled = true;
        if (idx === q.correct) {
            btn.classList.add('correct');
        } else if (idx === selectedIndex) {
            btn.classList.add('wrong');
        }
    });

    if (q.explanation) {
        const expBox = document.createElement('div');
        expBox.className = 'explanation-box';
        expBox.innerHTML = `<strong>व्याख्या:</strong> ${q.explanation}`;
        document.getElementById('explanationContainer').appendChild(expBox);
    }
};

// Navigation Button Listeners
prevBtn.addEventListener('click', () => {
    if (currentQuestionIndex > 0) {
        currentQuestionIndex--;
        loadQuiz();
    }
});

nextBtn.addEventListener('click', () => {
    const questions = mcqDatabase[currentChapterId];
    if (currentQuestionIndex < questions.length - 1) {
        currentQuestionIndex++;
        loadQuiz();
    }
});

// Jump to Question Event Listeners
if (jumpBtn) {
    jumpBtn.addEventListener('click', () => {
        const questions = mcqDatabase[currentChapterId] || [];
        const targetQ = parseInt(jumpInput.value, 10);

        if (targetQ >= 1 && targetQ <= questions.length) {
            currentQuestionIndex = targetQ - 1;
            loadQuiz();
        } else {
            alert(`कृपया 1 से ${questions.length} के बीच कोई वैध प्रश्न संख्या दर्ज करें।`);
        }
    });
}

if (jumpInput) {
    jumpInput.addEventListener('keypress', (e) => {
        if (e.key === 'Enter') {
            jumpBtn.click();
        }
    });
}

// Initial App Boot with Saved Preferences
window.addEventListener('DOMContentLoaded', () => {
    // Restore Theme
    const savedTheme = localStorage.getItem('cg_gk_theme');
    if (savedTheme === 'dark') {
        document.body.setAttribute('data-theme', 'dark');
        themeToggle.querySelector('.theme-icon').textContent = '☀️';
    }

    // Restore Reading Progress
    const savedChapter = localStorage.getItem('cg_gk_last_chapter');
    const savedQuestion = localStorage.getItem('cg_gk_last_question');

    if (savedChapter && savedQuestion) {
        currentChapterId = parseInt(savedChapter, 10);
        currentQuestionIndex = parseInt(savedQuestion, 10);
    }

    initChapterList();
    loadQuiz();
});
